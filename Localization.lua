local function ReplaceEdge(text, source, replacement, isPrefix)
    if isPrefix then
        if text:sub(1, #source) == source then
            return replacement .. text:sub(#source + 1)
        end
    elseif text:sub(-#source) == source then
        return text:sub(1, #text - #source) .. replacement
    end
end

function RexUI:LocalizeText(text)
    if text == nil or self.isGerman then
        return text
    end

    text = tostring(text)

    if ENGLISH[text] then
        return ENGLISH[text]
    end

    local translatedText = text

    for _, replacement in ipairs(PREFIXES) do
        local translated = ReplaceEdge(translatedText, replacement[1], replacement[2], true)
        if translated then
            translatedText = translated
            break
        end
    end

    for _, replacement in ipairs(SUFFIXES) do
        local translated = ReplaceEdge(translatedText, replacement[1], replacement[2], false)
        if translated then
            translatedText = translated
            break
        end
    end

    return translatedText
end

function RexUI:T(text)
    return self:LocalizeText(text)
end
